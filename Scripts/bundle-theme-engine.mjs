import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const packageRoot = new URL('node_modules/darkreader/', root);
let source = (await readFile(new URL('darkreader.js', packageRoot), 'utf8')).replaceAll('\r\n', '\n');
const license = await readFile(new URL('LICENSE', packageRoot), 'utf8');
// Upstream checks selectorText before the wildcard, but inline backgrounds
// have no selectorText. Apply the global image opt-out to those images too.
const original = `        if (!selectorText || selectors.length === 0) {
            return false;
        }
        if (selectors.some((s) => s === "*")) {
            return true;
        }`;
const replacement = `        if (selectors.some((s) => s === "*")) {
            return true;
        }
        if (!selectorText || selectors.length === 0) {
            return false;
        }`;
if (source.split(original).length !== 2) throw new Error('Review the image opt-out patch before updating Dark Reader.');
source = source.replace(original, replacement);
// Ignored stylesheet images are copied into an inline override. Resolve their
// URLs against the original stylesheet, so photos do not move to the page URL.
const imageOriginal = `            if (shouldIgnoreImage(rule.selectorText, ignoreImageSelectors)) {
                return value;
            }`;
const imageReplacement = `            if (shouldIgnoreImage(rule.selectorText, ignoreImageSelectors)) {
                const baseURL = rule.parentStyleSheet?.href || rule.parentStyleSheet?.ownerNode?.baseURI || document.baseURI;
                return value.replace(cssURLRegex, (match) => {
                    const url = getCSSURLValue(match);
                    return url ? \`url(\${JSON.stringify(getAbsoluteURL(baseURL, url))})\` : match;
                });
            }`;
if (source.split(imageOriginal).length !== 2) throw new Error('Review the image URL patch before updating Dark Reader.');
source = source.replace(imageOriginal, imageReplacement);
// Disabling both proxy options must also suppress the inline script itself.
// Safari sites with strict CSP cannot run it, and other sites should not have
// their page-world APIs patched just to apply an isolated extension's theme.
const proxyOriginal = `        {
            const proxyScript = createOrUpdateScript("darkreader--proxy");`;
const proxyReplacement = `        if (enableStyleSheetsProxy || enableCustomElementRegistryProxy) {
            const proxyScript = createOrUpdateScript("darkreader--proxy");`;
if (source.split(proxyOriginal).length !== 2) throw new Error('Review the proxy opt-out patch before updating Dark Reader.');
source = source.replace(proxyOriginal, proxyReplacement);
// The API build supplies its own chrome.runtime message transport. Keep that
// shim private: replacing Safari's transport would break Nightshift settings.
const bundled = `/* Generated by Scripts/bundle-theme-engine.mjs; do not edit.\n${license}*/\n(function () {\n    const chrome = { runtime: {} };\n    const exports = undefined, module = undefined, define = undefined;\n${source}\n}());\n`;
const output = new URL('Nightshift Extension/Resources/darkreader.js', root);
if (process.argv.includes('--check')) {
    if (await readFile(output, 'utf8') !== bundled) {
        throw new Error('The bundled theme engine is stale. Run npm run bundle:theme-engine.');
    }
    console.log('Bundled theme engine matches the pinned dependency and local patches.');
} else {
    await writeFile(output, bundled);
}
